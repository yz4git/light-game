test('movement, diagonal normalization and swept dash collision',()=>{const g=new Game();g.enemies=[];const before={...g.player};advance(g,1,{x:1,z:1});assert(distance(before,g.player)<4.75);const b={x:0,z:0,r:.4};moveBody(b,10,0,[{x:2,z:0,w:.2,d:5}]);assert(b.x<1.6);assert(!blocked(g.player.x,g.player.z,g.player.r,g.obstacles));});
test('battery exhaustion has recovery hysteresis and items are bounded',()=>{const g=new Game();g.enemies=[];advance(g,9,{light:true});assert(g.exhausted);assert(g.player.battery>0);advance(g,2,{light:false});assert(!g.exhausted);assert(g.player.battery<=100);g.player.battery=10;assert(g.consume('cell'));assert.equal(g.player.cells,1);g.player.hp=2;assert(g.consume('heal'));assert.equal(g.player.hp,4);assert.equal(g.player.heal,1);});
