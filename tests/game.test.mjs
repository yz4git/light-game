test('the key can be picked up unlit from the start and escape requires no kills', () => {
  for (const stage of [0, 1, 98, 997, 998]) {
    const g = new Game(stage);
    assert(g.keyAvailable);
    assert(!g.keyVisibleOnMap);
    Object.assign(g.player, g.config.exit);
    g.tick(1/60, {});
    assert.equal(g.status, 'playing', 'exit stays locked without the key');
    Object.assign(g.player, g.config.key);
    g.tick(1/60, {});
    assert(g.hasKey);
    assert(!g.keyVisibleOnMap, 'collected keys leave the map');
    Object.assign(g.player, g.config.exit);
    g.tick(1/60, {});
    assert.equal(g.status, 'clear');
    assert.equal(g.kills, 0);
    assert(g.enemies.every(e => e.hp === e.maxHp));
    assert.equal(g.events.filter(e => e.type === 'clear').length, 1);
    g.tick(1/60, {});
    assert.equal(g.events.filter(e => e.type === 'clear').length, 1);
  }
});

test('the minimap remembers a key only after an unobstructed beam reaches it', () => {
  const g = new Game();
  g.enemies = [];
  g.obstacles = [];
  Object.assign(g.player, {x:0, z:0, angle:0});
  g.config.key = {x:0, z:5};
  g.tick(1/60, {});
  assert(!g.keyVisibleOnMap, 'proximity without light does not reveal it');
  g.player.angle = Math.PI;
  g.tick(1/60, {light:true, aim:Math.PI});
  assert(!g.keyVisibleOnMap, 'the light must face the key');
  g.player.angle = 0;
  g.obstacles = [{x:0, z:2, w:3, d:1}];
  g.tick(1/60, {light:true, aim:0});
  assert(!g.keyVisibleOnMap, 'walls block discovery');
  g.obstacles = [];
  g.config.key.z = 14;
  g.tick(1/60, {light:true, aim:0});
  assert(!g.keyVisibleOnMap, 'the key must be in range');
  g.config.key.z = 5;
  g.tick(1/60, {light:true, aim:0});
  assert(g.keyVisibleOnMap);
  assert(!g.hasKey, 'revealing does not collect it');
  g.player.angle = Math.PI;
  g.tick(1/60, {});
  assert(g.keyVisibleOnMap, 'discovery survives switching the light off');
  assert.equal(g.events.filter(e => e.type === 'keyReveal').length, 1);
  Object.assign(g.player, g.config.key);
  g.tick(1/60, {});
  assert(g.hasKey);
  assert(!g.keyVisibleOnMap);
});
